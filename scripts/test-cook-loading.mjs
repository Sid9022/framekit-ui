// Run npm run dev first. Requires installed Chrome; screenshots are ignored by Git.
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { chromium } from 'playwright'

await fs.mkdir('.shots', { recursive: true })
const source = await fs.readFile('src/components/ui/cook-loading.tsx', 'utf8')
const embedded = Buffer.from(source.match(/const CHEF_SPRITE = 'data:image\/webp;base64,([^']+)'/)[1], 'base64')
assert.deepEqual(embedded, await fs.readFile('assets/cook-loading/chef-sprite.webp'), 'source and embedded asset match')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.FRAMEKIT_TEST_URL ?? 'http://127.0.0.1:5173/docs/cook-loading')
  const loader = page.locator('[data-state]').filter({ has: page.locator('canvas') }).first()
  await loader.waitFor()
  await loader.scrollIntoViewIfNeeded()
  await page.waitForTimeout(350)
  const canvas = loader.locator('canvas')
  const frame = () => canvas.evaluate(element => element.toDataURL())
  const first = await frame()
  await page.waitForTimeout(220)
  assert.notEqual(await frame(), first, 'chef cooks while loading')
  assert.equal(await loader.getByRole('progressbar').getAttribute('aria-valuenow'), null, 'no fake progress')
  await loader.getByRole('button', { name: 'Pause animation' }).focus()
  await page.keyboard.press('Enter')
  await page.waitForTimeout(250)
  assert.equal(await loader.getByRole('button', { name: 'Resume animation' }).getAttribute('aria-pressed'), 'true')
  const paused = await frame(); await page.waitForTimeout(200)
  assert.equal(await frame(), paused, 'pause freezes the illustration')
  await loader.screenshot({ path: '.shots/cook-light.png' })
  await page.getByRole('radio', { name: 'Dark preview' }).click()
  await page.waitForTimeout(400)
  await loader.screenshot({ path: '.shots/cook-dark.png' })
  await loader.getByRole('button', { name: 'Resume animation' }).press('Space')
  await page.getByLabel('Show real progress').check()
  assert.equal(await loader.getByRole('progressbar').getAttribute('aria-valuenow'), '42')
  await page.getByRole('button', { name: 'Ready', exact: true }).click()
  assert.equal(await loader.getAttribute('data-state'), 'done')
  assert.equal(await loader.getByRole('progressbar').getAttribute('aria-valuenow'), '100')
  assert.equal(await loader.getByRole('button').count(), 0)
  await page.waitForTimeout(400)
  const done = await frame(); await page.waitForTimeout(180)
  assert.equal(await frame(), done, 'completion stops cooking')
  await loader.screenshot({ path: '.shots/cook-done.png' })
  await page.getByRole('button', { name: 'Error', exact: true }).click()
  assert.equal(await loader.getByRole('progressbar').count(), 0)
  await loader.getByRole('button', { name: 'Try again' }).click()
  assert.equal(await loader.getAttribute('data-state'), 'loading')
  assert.equal(await loader.getByRole('progressbar').getAttribute('aria-valuenow'), '0')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForTimeout(300)
  assert.equal(await loader.getByRole('button', { name: /animation/ }).count(), 0)
  const still = await frame(); await page.waitForTimeout(200)
  assert.equal(await frame(), still, 'reduced motion remains still')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await loader.scrollIntoViewIfNeeded(); await page.waitForTimeout(250)
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  await page.waitForTimeout(300)
  const offscreen = await frame(); await page.waitForTimeout(220)
  assert.equal(await frame(), offscreen, 'offscreen animation stops')
  await loader.scrollIntoViewIfNeeded()
  await page.waitForTimeout(250)
  assert.notEqual(await frame(), offscreen, 'animation resumes in view')
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await loader.scrollIntoViewIfNeeded()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `no overflow at ${width}px`)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await loader.scrollIntoViewIfNeeded()
  const buttons = await loader.getByRole('button').evaluateAll(elements => elements.map(el => ({ width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height })))
  assert.ok(buttons.every(rect => rect.width >= 44 && rect.height >= 44), '44px touch targets')
  await loader.screenshot({ path: '.shots/cook-mobile.png' })
  assert.deepEqual(errors, [], 'no browser errors')
  console.log('PASS: asset integrity, cooking, keyboard pause/resume, progress, completion, error/retry, reduced motion, offscreen suspension, responsive layout and touch targets.')
} finally {
  await browser.close()
}
