// Start npm run dev first. Uses the existing Playwright dependency and installed Chrome.
// Override FRAMEKIT_TEST_URL to exercise a separate consuming app with the zero-prop demo.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const url = process.env.FRAMEKIT_TEST_URL ?? 'http://127.0.0.1:5173/docs/particle-mesh-gallery'
await mkdir('.shots', { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(url)
  const gallery = page.getByRole('region', { name: 'Selected work', exact: true })
  await gallery.waitFor()
  const stage = gallery.locator('button[aria-pressed]').first()
  await stage.click()
  assert.equal(await stage.getAttribute('aria-pressed'), 'true', 'click reveals')
  await stage.dblclick({ delay: 70 })
  assert.equal(await stage.getAttribute('aria-pressed'), 'false', 'double click reforms')
  await stage.press('Enter')
  assert.equal(await stage.getAttribute('aria-pressed'), 'true', 'Enter reveals')
  await page.waitForTimeout(1400)
  await gallery.screenshot({ path: '.shots/particle-image.png' })
  await stage.press('Escape')
  assert.equal(await stage.getAttribute('aria-pressed'), 'false', 'Escape reforms')
  await stage.press('ArrowRight')
  assert.match(await gallery.innerText(), /The quiet distance/)
  await stage.press('ArrowLeft')
  await gallery.getByRole('button', { name: 'Pause rotation' }).click()
  await page.waitForTimeout(1400)
  const canvas = gallery.locator('canvas')
  const before = await canvas.evaluate(el => el.toDataURL())
  await page.waitForTimeout(200)
  assert.equal(await canvas.evaluate(el => el.toDataURL()), before, 'paused canvas settles')
  await gallery.screenshot({ path: '.shots/particle-light.png' })
  // Force the nearest scope, including the docs' independently themed preview.
  await gallery.evaluate(el => { const scope = el.parentElement; scope.classList.remove('light'); scope.classList.add('dark') })
  await page.waitForTimeout(200)
  await gallery.screenshot({ path: '.shots/particle-dark.png' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForTimeout(200)
  assert.equal(await gallery.getByRole('button', { name: /rotation/ }).count(), 0)
  await stage.press('Space')
  assert.equal(await stage.getAttribute('aria-pressed'), 'true')
  await stage.press('Space')
  assert.equal(await stage.getAttribute('aria-pressed'), 'false')
  const reducedFrame = await canvas.evaluate(el => el.toDataURL())
  await page.waitForTimeout(150)
  assert.equal(await canvas.evaluate(el => el.toDataURL()), reducedFrame, 'reduced motion is static')

  const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  const mobile = await touch.newPage()
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.goto(url)
  const mobileGallery = mobile.getByRole('region', { name: 'Selected work', exact: true })
  const touchStage = mobileGallery.locator('button[aria-pressed]').first()
  await touchStage.tap()
  assert.equal(await touchStage.getAttribute('aria-pressed'), 'true', 'touch tap reveals')
  await mobile.waitForTimeout(400)
  await touchStage.tap()
  await touchStage.tap()
  assert.equal(await touchStage.getAttribute('aria-pressed'), 'false', 'double touch reforms')
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, '390px has no page overflow')
  const sizes = await mobileGallery.locator('button').evaluateAll(buttons => buttons.map(button => ({ width: button.getBoundingClientRect().width, height: button.getBoundingClientRect().height })))
  assert.ok(sizes.every(size => size.width >= 44 && size.height >= 44), 'touch targets at least 44px')
  await mobile.waitForTimeout(1400)
  await mobileGallery.screenshot({ path: '.shots/particle-mobile.png' })
  assert.deepEqual(errors, [], 'no uncaught browser errors')
  console.log('PASS: pointer, double touch, keyboard, navigation, pause, reduced motion, 390px overflow, touch targets, and screenshots.')
} finally {
  await browser.close()
}
